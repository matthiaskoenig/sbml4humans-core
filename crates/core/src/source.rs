//! OMEX, gzip and standalone source envelopes using the shared metadata infrastructure.
use crate::ReportError;
use indexmap::IndexMap;
use md5::{Digest, Md5};
use pymetadata_core::{
    formats::{guess_format, lookup_format},
    location::normalize_location,
    manifest::{Entry, Manifest},
    zip::Reader,
};
use sbml4humans_report::{DebugInfo, ReportEntry, SourceDocument};
use serde::{Deserialize, Serialize};
use std::collections::{BTreeMap, HashSet};

/// Resource limits applied before archive members are inflated.
#[derive(Clone, Debug, Deserialize, Serialize)]
#[serde(default, rename_all = "camelCase")]
pub struct SourceLimits {
    /// Maximum input and total uncompressed source bytes.
    pub max_content_size: usize,
    /// Maximum raw ZIP members, including directory entries.
    pub max_archive_entries: usize,
    /// Maximum compression ratio above the minimum member size.
    pub max_compression_ratio: u64,
    /// Smaller members are exempt from the compression-ratio check.
    pub compression_ratio_min_size: u64,
}
impl Default for SourceLimits {
    fn default() -> Self {
        Self {
            max_content_size: crate::MAX_INPUT_BYTES,
            max_archive_entries: 1000,
            max_compression_ratio: 200,
            compression_ratio_min_size: 1024 * 1024,
        }
    }
}
/// Host-supplied identity, model location and work limits for one source.
#[derive(Clone, Debug, Deserialize, Serialize)]
#[serde(default, rename_all = "camelCase")]
pub struct SourceOptions {
    /// Request identity, generated by the host rather than a WASM system import.
    pub uid: String,
    /// Location of a standalone model. Archives retain their own manifest locations.
    pub location: String,
    /// The maximum elements instantiated by comp before equation analysis is skipped.
    pub max_expanded_elements: usize,
    /// Input/decompression limits, independent for each request.
    pub limits: SourceLimits,
}
impl Default for SourceOptions {
    fn default() -> Self {
        Self {
            uid: String::new(),
            location: "./model.xml".into(),
            max_expanded_elements: 10000,
            limits: SourceLimits::default(),
        }
    }
}
/// The public COMBINE manifest, including its two derived entries.
#[derive(Debug, Serialize)]
pub struct SourceManifest {
    /// Entries in application order.
    pub entries: Vec<Entry>,
}
/// The complete application response of one SBML source or COMBINE archive.
#[derive(Debug, Serialize)]
pub struct SourceResponse {
    /// Request identity supplied by the host.
    pub uid: String,
    /// Every entry, including non-SBML files.
    pub manifest: SourceManifest,
    /// Complete reports in manifest order.
    pub reports: IndexMap<String, ReportEntry>,
}
fn archive_error(error: pymetadata_core::error::OmexError) -> ReportError {
    use pymetadata_core::error::OmexError::*;
    let kind = match error {
        Refused(_) | Password(_) | Unsupported(_) => "refused",
        _ => "malformed",
    };
    ReportError {
        kind,
        message: error.to_string(),
    }
}
fn sbml(format: &str) -> bool {
    format.contains("identifiers.org/combine.specifications/sbml")
        || format.contains("identifiers.org/combine.specifications:sbml")
}
fn derived(location: &str) -> bool {
    matches!(location, "." | "./manifest.xml")
}
type OpenedArchive = (Reader, Vec<Entry>, BTreeMap<String, usize>);
fn archive_members(
    source: &[u8],
    limits: &SourceLimits,
) -> Result<Option<OpenedArchive>, ReportError> {
    // Self-extracting ZIPs can carry a prefix, so detection uses the end record as well.
    let tail = &source[source.len().saturating_sub(65557)..];
    if !source.starts_with(b"PK") && !tail.windows(4).any(|s| s == b"PK\x05\x06") {
        return Ok(None);
    }
    let reader = Reader::with_max_inflated_size(source.to_vec(), limits.max_content_size)
        .map_err(archive_error)?;
    if reader.members().len() > limits.max_archive_entries {
        return Err(ReportError::refused(format!(
            "The archive has more than {} entries.",
            limits.max_archive_entries
        )));
    }
    let mut total = 0u64;
    let mut members = BTreeMap::new();
    for (index, member) in reader.members().iter().enumerate() {
        total = total.saturating_add(member.uncompressed_size);
        if total > limits.max_content_size as u64 {
            return Err(ReportError::refused(
                "The uncompressed archive exceeds the source limit.",
            ));
        }
        if member.uncompressed_size > limits.compression_ratio_min_size
            && member.uncompressed_size
                > member
                    .compressed_size
                    .saturating_mul(limits.max_compression_ratio)
        {
            return Err(ReportError::refused(format!(
                "The entry '{}' of the archive is compressed more than {} times.",
                member.name, limits.max_compression_ratio
            )));
        }
        if !member.name.ends_with('/') {
            members.insert(
                normalize_location(&member.name).map_err(archive_error)?,
                index,
            );
        }
    }
    let Some(&manifest) = members.get("./manifest.xml") else {
        return Ok(None);
    };
    let manifest = reader
        .inflate(&reader.members()[manifest])
        .map_err(archive_error)?;
    let xml = std::str::from_utf8(&manifest).map_err(|e| ReportError {
        kind: "malformed",
        message: format!("The archive manifest is not UTF-8: {e}"),
    })?;
    let declared = Manifest::parse_declared(xml).map_err(archive_error)?;
    let mut entries = Manifest::default().entries().to_vec();
    let mut seen = HashSet::new();
    for entry in &declared {
        seen.insert(entry.location.clone());
        if !derived(&entry.location) && members.contains_key(&entry.location) {
            entries.push(entry.clone());
        }
    }
    for (location, &index) in &members {
        if derived(location) || seen.contains(location) {
            continue;
        }
        let suffix = pymetadata_core::location::suffix(location).to_ascii_lowercase();
        let head = if suffix == "xml" {
            reader
                .inflate_head(&reader.members()[index], 256)
                .unwrap_or_default()
        } else {
            Vec::new()
        };
        let format = guess_format(&suffix, &head);
        entries.push(
            Entry::new(location, format, format == lookup_format("sed-ml"))
                .map_err(archive_error)?,
        );
    }
    Ok(Some((reader, entries, members)))
}
/// Read and report plain/gzipped SBML or a COMBINE archive, entirely in memory.
///
/// # Errors
/// Invalid XML/ZIP or a declared unreadable SBML entry aborts the source; limits refuse it before inflation.
pub fn source(source: &[u8], options: &SourceOptions) -> Result<SourceResponse, ReportError> {
    if source.len() > options.limits.max_content_size {
        return Err(ReportError::refused(
            "The source exceeds the input size limit.",
        ));
    }
    let mut inputs = Vec::new();
    let entries =
        if let Some((reader, entries, members)) = archive_members(source, &options.limits)? {
            for entry in entries.iter().filter(|entry| sbml(&entry.format)) {
                let index = members[&entry.location];
                inputs.push((
                    entry.location.clone(),
                    reader
                        .inflate(&reader.members()[index])
                        .map_err(archive_error)?,
                ));
            }
            entries
        } else {
            let mut entries = Manifest::default().entries().to_vec();
            let entry = Entry::new(&options.location, lookup_format("sbml"), true)
                .map_err(archive_error)?;
            inputs.push((entry.location.clone(), source.to_vec()));
            entries.push(entry);
            entries
        };
    let documents = inputs
        .iter()
        .map(|(_, bytes)| {
            let decoded = crate::decode(bytes, options.limits.max_content_size)?;
            let document = sbml4humans_reader::read(&decoded).map_err(|e| ReportError {
                kind: "malformed",
                message: e.to_string(),
            })?;
            if document.model.is_none() {
                return Err(ReportError {
                    kind: "malformed",
                    message: "No SBML model could be read.".into(),
                });
            }
            Ok(document)
        })
        .collect::<Result<Vec<_>, ReportError>>()?;
    let checksums: Vec<_> = inputs
        .iter()
        .map(|(_, bytes)| {
            Md5::digest(bytes)
                .iter()
                .map(|byte| format!("{byte:02x}"))
                .collect::<String>()
        })
        .collect();
    let sources: Vec<_> = inputs
        .iter()
        .zip(&documents)
        .zip(&checksums)
        .map(|(((location, _), document), checksum)| SourceDocument {
            location,
            document,
            checksum: Some(checksum),
        })
        .collect();
    let locations: Vec<_> = entries.iter().map(|e| e.location.as_str()).collect();
    let built = sbml4humans_report::build_many(&sources, &locations, options.max_expanded_elements)
        .map_err(|e| ReportError {
            kind: "malformed",
            message: e.to_string(),
        })?;
    let reports = inputs
        .into_iter()
        .zip(built)
        .map(|((location, _), report)| {
            (
                location,
                ReportEntry {
                    report,
                    debug: DebugInfo {
                        json_report_time: "0.0 [s]".into(),
                    },
                },
            )
        })
        .collect();
    Ok(SourceResponse {
        uid: options.uid.clone(),
        manifest: SourceManifest { entries },
        reports,
    })
}
/// Serialize a complete source response without creating host objects per SBML element.
///
/// # Errors
/// Returns input, report or serialization failures, as [`source`].
pub fn source_json(input: &[u8], options: &SourceOptions) -> Result<Vec<u8>, ReportError> {
    serde_json::to_vec(&source(input, options)?).map_err(|e| ReportError {
        kind: "internal",
        message: e.to_string(),
    })
}
